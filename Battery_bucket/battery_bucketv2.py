capacity_mwh = 100.0
stored_mwh = 80.0
temp_c = 25.0
time_step_hr = 0.25

def get_battery_power(city_load, grid_freq, battery_percent):
  power = 0.0

  if city_load > 80 and battery_percent > 15:
    power += (city_load - 80)

  if grid_freq < 49.98 and battery_percent:
    drop = 50 - grid_freq
    power += drop * 12.25

  return min(25.0, power)


grid_data = [
    (65.0, 50.00),  # Normal day -> 0 MW used
    (92.0, 50.00),  # Evening peak -> 12 MW used
    (90.0, 49.80),  # Peak + frequency dip -> 12.5 MW used
    (70.0, 49.60),  # Big generator trip -> 5 MW used
]

print("Step | Load | Freq | BESS Power | Charge(%) | temp (°C)")
print("-" * 60)

for step, (city_load, grid_freq) in enumerate(grid_data, start=1):
  soc_percent = (stored_mwh / capacity_mwh) * 100

  discharge_mw = get_battery_power(city_load, grid_freq, soc_percent)

  energy_used = discharge_mw * time_step_hr
  stored_mwh = max(0.0, stored_mwh - energy_used)
  new_soc = (stored_mwh / capacity_mwh) * 100

  c_rate = discharge_mw / capacity_mwh
  heat_added = 15.0 * (c_rate ** 2) * time_step_hr
  heat_lost = 0.3 * (temp_c - 25.00) * time_step_hr
  temp_c = max(25.0, temp_c + heat_added - heat_lost)

  print(f"{step:4d} | {city_load:4.0f} | {grid_freq:5.2f} | {discharge_mw:7.2f} MW | {new_soc:9.1f}% | {temp_c:8.2f}°C)")